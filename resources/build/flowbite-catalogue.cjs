/**
 * Generates resources/styles/frontend/vendor/_flowbite-catalogue.scss:
 * the Flowbite rules the catalogue uses, scoped to its .loc-catalogue wrapper.
 *
 * Flowbite used to be @imported whole from a CDN. Its global Tailwind reset and
 * utilities (.container, .hidden, .flex, headings, images, links) restyled the
 * theme on every page that loaded the catalogue stylesheet.
 *
 * - Selectors without classes (the reset, form base styles) are kept and scoped;
 *   html/body rules are dropped (page-level, the theme owns them).
 * - Class selectors are kept only when every class appears in the catalogue's
 *   templates (resources/scripts/frontend, app/src, views).
 * - Scoping uses :where(.loc-catalogue), which adds no specificity, so the
 *   cascade inside the catalogue is the same as before.
 * - Rules that need a .dark ancestor and unused @keyframes are dropped.
 *
 * Run: yarn flowbite:scope   (after changing templates or the flowbite version)
 */
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');

const root = path.resolve(__dirname, '../..');
const SCOPE = ':where(.loc-catalogue)';
const out = path.join(root, 'resources/styles/frontend/vendor/_flowbite-catalogue.scss');

function walk(dir, exts, files = []) {
  if (!fs.existsSync(dir)) return files;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, exts, files);
    else if (exts.includes(path.extname(e.name))) files.push(p);
  }
  return files;
}

// Every token that could be a class name in the templates. Over-inclusive on purpose.
const used = new Set();
const sources = [
  ...walk(path.join(root, 'resources/scripts/frontend'), ['.vue', '.js']),
  ...walk(path.join(root, 'app/src'), ['.php']),
  ...walk(path.join(root, 'views'), ['.php']),
];
for (const f of sources) {
  for (const t of fs.readFileSync(f, 'utf8').split(/[\s"'`<>={}(),;\\]+/)) used.add(t);
}

const unescape = (c) => c.replace(/\\(.)/g, '$1');
const classesOf = (sel) => (sel.match(/\.(?:\\.|[\w-])+/g) || []).map((c) => unescape(c.slice(1)));
const ROOTS = /^(html|body|:root|:host)(?![\w-])/;

function scopeSelector(sel) {
  sel = sel.trim();
  if (ROOTS.test(sel)) return []; // page-level (html/body); the theme sets these
  if (sel === '*') return [SCOPE, `${SCOPE} *`];
  return [`${SCOPE} ${sel}`];
}

const css = fs.readFileSync(require.resolve('flowbite/dist/flowbite.min.css'), 'utf8');
const ast = postcss.parse(css);
const animations = new Set();

ast.walkRules((rule) => {
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  const kept = [];
  for (const sel of rule.selectors) {
    const cls = classesOf(sel);
    if (cls.includes('dark')) continue;
    if (cls.every((c) => used.has(c))) kept.push(...scopeSelector(sel));
  }
  if (!kept.length) { rule.remove(); return; }
  rule.selectors = [...new Set(kept)];
  rule.walkDecls(/^animation(-name)?$/, (d) => d.value.split(/[\s,]+/).forEach((v) => animations.add(v)));
});
ast.walkAtRules((at) => {
  if (/keyframes$/.test(at.name)) { if (!animations.has(at.params)) at.remove(); return; }
  if (at.nodes && at.nodes.length === 0) at.remove();
});
ast.walkAtRules((at) => { if (at.nodes && at.nodes.length === 0) at.remove(); });

const version = require('flowbite/package.json').version;
fs.writeFileSync(out, `/* Generated by resources/build/flowbite-catalogue.cjs from flowbite ${version}. Do not edit. */\n${ast.toString()}\n`);
console.log(`Wrote ${path.relative(root, out)} (${fs.statSync(out).size} bytes, ${sources.length} template files scanned)`);
